import os
import pandas as pd
from src.config import MARKER_NAME_MAP

class FeatureEngineer:
    def __init__(self, canonical_marker_columns=None, sampling_rate=50.0):
        self.canonical_marker_columns = canonical_marker_columns
        self.sampling_rate = sampling_rate
        self.time_diff = 1.0 / sampling_rate if sampling_rate > 0 else 0.02

    def process_features(self, trc_df: pd.DataFrame) -> pd.DataFrame:
        """
        Computes velocity, acceleration, and relative positions.
        """
        if trc_df is None or trc_df.empty:
            return trc_df

        df = trc_df.copy()

        # 1. Velocity and Acceleration
        # Identify base columns (markers) to compute features for.
        # Exclude already existing feature columns if any.
        # Exclude already-derived columns and CoM kinematic cols added by the
        # biomechanical preprocessor (those are appended after this function runs).
        base_cols = [c for c in df.columns if not (
            c.endswith('_vel') or c.endswith('_acc')
            or c.startswith('rel_') or c.startswith('COM_')
        )]

        new_cols_dict = {}
        # Ablation switch: FEATURES_DERIVED=0 skips velocity/acceleration (columns zero-filled on reindex)
        if os.getenv('FEATURES_DERIVED', '1') == '0':
            base_cols = []
        for col in base_cols:
            vel_col_name = f"{col}_vel"
            acc_col_name = f"{col}_acc"

            vel_series = df[col].diff() / self.time_diff
            acc_series = vel_series.diff() / self.time_diff

            new_cols_dict[vel_col_name] = vel_series
            new_cols_dict[acc_col_name] = acc_series

        if new_cols_dict:
            new_cols_df = pd.DataFrame(new_cols_dict)
            df = pd.concat([df, new_cols_df], axis=1)

        # 2. Relative Positions
        marker_pairs = [
            ('LSHO', 'LELBL'), ('LELBL', 'LWRL'), ('RSHO', 'RELBL'), ('RELBL', 'RWRL'),
            ('LKNE', 'LANKL'), ('LANKL', 'LTOE'), ('RKNE', 'RANKM'), ('RANKM', 'RTOE'),
            ('LSHO', 'RSHO'), ('LASI', 'LSHO')
        ]

        relative_pos_cols = {}
        # Ablation switch: FEATURES_REL=0 skips relative-position features (zero-filled on reindex)
        if os.getenv('FEATURES_REL', '1') == '0':
            marker_pairs = []
        for marker1_short, marker2_short in marker_pairs:
            marker1_full = MARKER_NAME_MAP.get(marker1_short)
            marker2_full = MARKER_NAME_MAP.get(marker2_short)

            if marker1_full and marker2_full:
                for axis in ['X', 'Y', 'Z']:
                    col1 = f"{marker1_full}_{axis}"
                    col2 = f"{marker2_full}_{axis}"

                    if col1 in df.columns and col2 in df.columns:
                        new_col_name = f"rel_{marker1_short}_{marker2_short}_{axis}"
                        relative_pos_cols[new_col_name] = df[col1] - df[col2]

        if relative_pos_cols:
            rel_df = pd.DataFrame(relative_pos_cols)
            df = pd.concat([df, rel_df], axis=1)

        # Fill NaNs generated by diff() (first 2 rows)
        df.fillna(0.0, inplace=True)

        # 3. Reindex to Canonical
        if self.canonical_marker_columns:
            # Ensure we have all expected columns, fill missing with 0
            df = df.reindex(columns=self.canonical_marker_columns, fill_value=0.0)

        return df
